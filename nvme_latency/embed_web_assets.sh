#!/bin/bash
# Generates a C++ source file embedding static web files.
# Usage: embed_web_assets.sh OUTPUT.cc FILE...
set -euo pipefail

out="$1"
shift

# Raw string delimiters are limited to 16 characters.
delim='NVME_WEB_ASSET'

{
  echo '// Generated by embed_web_assets.sh. Do not edit.'
  echo '#include "nvme_latency/web_assets.h"'
  echo
  echo 'namespace nvme_bpf {'
  echo 'namespace {'
  i=0
  for f in "$@"; do
    if grep -q ")${delim}\"" "$f"; then
      echo "embed_web_assets.sh: $f contains the raw string delimiter" >&2
      exit 1
    fi
    echo "constexpr char kAsset${i}[] = R\"${delim}("
    cat "$f"
    echo ")${delim}\";"
    i=$((i + 1))
  done
  echo
  echo 'constexpr WebAsset kAssets[] = {'
  i=0
  for f in "$@"; do
    name="$(basename "$f")"
    case "$name" in
      *.html) type='text/html; charset=utf-8' ;;
      *.css) type='text/css; charset=utf-8' ;;
      *.js) type='text/javascript; charset=utf-8' ;;
      *.svg) type='image/svg+xml' ;;
      *.json) type='application/json' ;;
      *) type='application/octet-stream' ;;
    esac
    echo "    {\"/${name}\", \"${type}\", absl::string_view(kAsset${i}, sizeof(kAsset${i}) - 1)},"
    i=$((i + 1))
  done
  echo '};'
  echo
  echo '}  // namespace'
  echo
  echo 'absl::Span<const WebAsset> EmbeddedWebAssets() { return kAssets; }'
  echo
  echo '}  // namespace nvme_bpf'
} > "$out"
